//
//  ClipboardManager.swift
//  boringNotch
//
//  Clipboard history (like Windows Win+V). Polls the general pasteboard's
//  change count and keeps the most recent entries in memory only.
//  Entries marked as concealed/transient (password managers etc.) are never stored.
//

import AppKit
import Combine
import UniformTypeIdentifiers

struct ClipboardItem: Identifiable, Equatable {
    enum Content: Equatable {
        case text(String)
        case image(NSImage, Data)      // display image + original data (PNG/TIFF)
        case files([URL])
    }

    let id = UUID()
    let content: Content
    let date: Date
    let sourceAppName: String?
    let sourceAppIcon: NSImage?
    var isPinned: Bool = false

    static func == (lhs: ClipboardItem, rhs: ClipboardItem) -> Bool {
        lhs.id == rhs.id && lhs.isPinned == rhs.isPinned
    }

    /// Identity used to de-duplicate repeated copies of the same content.
    var dedupeKey: String {
        switch content {
        case .text(let s): return "t:" + s
        case .image(_, let data): return "i:\(data.count):\(data.prefix(64).hashValue)"
        case .files(let urls): return "f:" + urls.map(\.path).joined(separator: "|")
        }
    }
}

@MainActor
final class ClipboardManager: ObservableObject {
    static let shared = ClipboardManager()

    @Published private(set) var items: [ClipboardItem] = []
    /// Briefly set after an item is copied back, for UI feedback.
    @Published private(set) var lastCopiedID: UUID?

    private let maxItems = 50
    private let maxImageBytes = 15 * 1024 * 1024
    private let pasteboard = NSPasteboard.general
    private var lastChangeCount: Int
    private var timer: Timer?

    /// Types that password managers and other apps use to say "don't record this".
    /// See http://nspasteboard.org
    private let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
        .init("com.agilebits.onepassword"),
        .init("com.typeit4me.clipping"),
        .init("de.petermaurer.TransientPasteboardType"),
        .init("Pasteboard generator type"),
    ]

    private init() {
        lastChangeCount = NSPasteboard.general.changeCount
    }

    func start() {
        guard timer == nil else { return }
        lastChangeCount = pasteboard.changeCount
        let t = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            Task { @MainActor in self?.poll() }
        }
        t.tolerance = 0.2
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    // MARK: - Capture

    private func poll() {
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        capture()
    }

    private func capture() {
        let types = Set(pasteboard.types ?? [])
        guard !types.isEmpty, types.isDisjoint(with: ignoredTypes) else { return }

        let front = NSWorkspace.shared.frontmostApplication
        let content: ClipboardItem.Content?

        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty
        {
            content = .files(urls)
        } else if let data = imageData(), let image = NSImage(data: data) {
            content = .image(image, data)
        } else if let string = pasteboard.string(forType: .string),
                  !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty
        {
            content = .text(string)
        } else {
            content = nil
        }

        guard let content else { return }
        add(ClipboardItem(
            content: content,
            date: Date(),
            sourceAppName: front?.localizedName,
            sourceAppIcon: front?.icon
        ))
    }

    private func imageData() -> Data? {
        for type in [NSPasteboard.PasteboardType.png, .tiff] {
            if let data = pasteboard.data(forType: type), data.count <= maxImageBytes {
                return data
            }
        }
        return nil
    }

    private func add(_ item: ClipboardItem) {
        // Re-copying existing content moves it to the top instead of duplicating it.
        var newItem = item
        if let index = items.firstIndex(where: { $0.dedupeKey == item.dedupeKey }) {
            newItem.isPinned = items[index].isPinned
            items.remove(at: index)
        }
        items.insert(newItem, at: 0)
        trim()
    }

    private func trim() {
        while items.count > maxItems, let index = items.lastIndex(where: { !$0.isPinned }) {
            items.remove(at: index)
        }
    }

    // MARK: - Actions

    /// Puts an item back on the clipboard and moves it to the top of the history.
    func copy(_ item: ClipboardItem) {
        pasteboard.clearContents()
        switch item.content {
        case .text(let s):
            pasteboard.setString(s, forType: .string)
        case .image(let image, _):
            pasteboard.writeObjects([image])
        case .files(let urls):
            pasteboard.writeObjects(urls as [NSURL])
        }
        // Don't re-capture our own write.
        lastChangeCount = pasteboard.changeCount

        if let index = items.firstIndex(where: { $0.id == item.id }) {
            let moved = items.remove(at: index)
            items.insert(moved, at: 0)
        }
        lastCopiedID = item.id
        Task { [weak self] in
            try? await Task.sleep(for: .seconds(1.2))
            if self?.lastCopiedID == item.id { self?.lastCopiedID = nil }
        }
    }

    func togglePin(_ item: ClipboardItem) {
        guard let index = items.firstIndex(where: { $0.id == item.id }) else { return }
        items[index].isPinned.toggle()
    }

    func remove(_ item: ClipboardItem) {
        items.removeAll { $0.id == item.id }
    }

    /// Clears everything except pinned items.
    func clearUnpinned() {
        items.removeAll { !$0.isPinned }
    }

    /// Item provider for dragging an entry into another app.
    func itemProvider(for item: ClipboardItem) -> NSItemProvider {
        switch item.content {
        case .text(let s):
            return NSItemProvider(object: s as NSString)
        case .image(let image, _):
            return NSItemProvider(object: image)
        case .files(let urls):
            return NSItemProvider(contentsOf: urls.first) ?? NSItemProvider()
        }
    }
}
